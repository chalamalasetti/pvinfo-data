#!/usr/bin/env node
// Builds this repository's GitHub Actions workflows from the job definitions in the
// private code repository (chalamalasetti/PV-Info, .github/workflows).
//
// Why: public repositories get GitHub Actions minutes free, private ones do not. The code
// stays private; each job here checks it out for the run with a read-only token
// (PVINFO_CODE_TOKEN) and publishes to this repository as before.
//
//   node scripts/build-jobs.mjs <code-repo-workflows-dir> <output-workflows-dir>
//
// Rules:
// - Scheduled and manual triggers are kept; push and pull_request triggers are dropped.
// - Every actions/checkout of the job's own repository checks out PV-Info instead, with
//   persisted credentials off, and `origin` is pointed at this public repository so cache
//   branches are fetched from and pushed to here.
// - ci.yml becomes pv-info-checks.yml: every 30 minutes it tests new commits of open
//   PV-Info pull requests (tested as their merge with main) and of main, and posts the
//   result on the head commit as a status.
// - curated-requirements.yml publishes the newest curation commit (any claude/** branch
//   or main) every 30 minutes instead of on each push.
// - Files this script wrote earlier whose source is gone are removed.
import fs from 'node:fs';
import path from 'node:path';
import {parse, stringify} from 'yaml';

export const CODE_REPO = 'chalamalasetti/PV-Info';
export const CODE_TOKEN = '${{ secrets.PVINFO_CODE_TOKEN }}';
export const MARKER = '# Generated by scripts/build-jobs.mjs from chalamalasetti/PV-Info';
const SKIP = new Set(['data-repo-copy.yml']);
const RENAME = {'ci.yml': 'pv-info-checks.yml'};
const CHECK_CONTEXT = 'PV-Info checks';
const POLL = '*/30 * * * *';

// Per-file text fixes for steps that name the running repository on purpose.
const OVERRIDES = {
  // The backup mirror copies the code repository, not this one.
  'mirror.yml': run => run.replaceAll('${GITHUB_REPOSITORY}', CODE_REPO),
};
const OVERRIDE_ENV = {
  'mirror.yml': env => env && env.SRC_TOKEN ? {...env, SRC_TOKEN: CODE_TOKEN} : env,
};

const ownCheckout = step => typeof step?.uses === 'string' && step.uses.startsWith('actions/checkout@') && !step.with?.repository && !step.with?.path;

export function rewriteSteps(steps = [], {ref = 'main', file = ''} = {}) {
  const out = [];
  for (const original of steps) {
    const step = structuredClone(original);
    if (OVERRIDES[file] && typeof step.run === 'string') step.run = OVERRIDES[file](step.run);
    if (OVERRIDE_ENV[file]) step.env = OVERRIDE_ENV[file](step.env);
    if (ownCheckout(step)) {
      step.with = {...(step.with || {}), repository: CODE_REPO, ref, token: CODE_TOKEN, 'persist-credentials': false};
      out.push(step, {name: 'Use the public data repository as origin', run: 'git remote set-url origin "https://github.com/${{ github.repository }}.git"'});
      continue;
    }
    out.push(step);
  }
  return out;
}

function keepTriggers(on) {
  if (!on || typeof on !== 'object' || Array.isArray(on)) {
    const list = [].concat(on || []);
    return list.includes('workflow_dispatch') ? {workflow_dispatch: null} : null;
  }
  const kept = {};
  if (on.schedule) kept.schedule = on.schedule;
  if ('workflow_dispatch' in on) kept.workflow_dispatch = on.workflow_dispatch;
  return Object.keys(kept).length ? kept : null;
}

const statusStep = (job, state) => ({
  name: state === 'pending' ? 'Mark the PV-Info commit as being checked' : 'Post the result on the PV-Info commit',
  ...(state === 'pending' ? {} : {if: 'always()'}),
  uses: 'actions/github-script@v7',
  with: {
    'github-token': CODE_TOKEN,
    script: [
      `const state = ${state === 'pending' ? "'pending'" : "'${{ job.status }}' === 'success' ? 'success' : 'failure'"};`,
      `await github.rest.repos.createCommitStatus({owner: 'chalamalasetti', repo: 'PV-Info', sha: '\${{ matrix.target.sha }}', state,`,
      `  context: '${CHECK_CONTEXT} / ${job}', target_url: \`\${context.serverUrl}/\${context.repo.owner}/\${context.repo.repo}/actions/runs/\${context.runId}\`,`,
      `  description: state === 'pending' ? 'Running in pvinfo-data' : 'Ran in pvinfo-data: ' + state});`,
    ].join('\n'),
  },
});

const PLAN_SCRIPT = `
// A pull request is tested as GitHub's merge commit with main (as pull_request CI did), so a
// branch made before a newer test landed on main is not failed for it. The result is posted on
// the pull request's head commit.
const owner = 'chalamalasetti', repo = 'PV-Info', wanted = '\${{ inputs.sha }}'.trim(), recheck = '\${{ inputs.recheck }}' === 'true';
const targets = [];
if (wanted) targets.push({sha: wanted, ref: wanted, label: 'manual'});
else {
  const pulls = await github.paginate(github.rest.pulls.list, {owner, repo, state: 'open', sort: 'updated', direction: 'desc', per_page: 100});
  const main = (await github.rest.repos.getBranch({owner, repo, branch: 'main'})).data.commit.sha;
  const candidates = [{sha: main, ref: main, label: 'main'}];
  for (const p of pulls) {
    if (p.head.repo?.full_name?.toLowerCase() !== 'chalamalasetti/pv-info') continue;
    candidates.push({sha: p.head.sha, number: p.number, label: '#' + p.number});
  }
  for (const c of candidates) {
    if (targets.length >= 4) break;
    if (targets.some(t => t.sha === c.sha)) continue;
    if (!recheck) {
      const statuses = await github.paginate(github.rest.repos.listCommitStatusesForRef, {owner, repo, ref: c.sha, per_page: 100});
      if (statuses.some(s => s.context.startsWith('${CHECK_CONTEXT} /'))) continue;
    }
    if (c.number) {
      const pr = (await github.rest.pulls.get({owner, repo, pull_number: c.number})).data;
      if (pr.mergeable === false || !pr.merge_commit_sha) {
        await github.rest.repos.createCommitStatus({owner, repo, sha: c.sha, state: 'error', context: '${CHECK_CONTEXT} / merge', description: 'Has merge conflicts with main; resolve them to run the checks'});
        continue;
      }
      c.ref = pr.merge_commit_sha;
    }
    targets.push(c);
  }
}
core.info('Commits to check: ' + (targets.map(t => t.label + ' ' + t.sha.slice(0, 7)).join(', ') || 'none'));
core.setOutput('targets', JSON.stringify(targets));`;

function ciWorkflow(doc, file) {
  const jobs = {
    plan: {
      'runs-on': 'ubuntu-latest',
      outputs: {targets: '${{ steps.plan.outputs.targets }}'},
      steps: [{id: 'plan', name: 'Find new PV-Info commits to check', uses: 'actions/github-script@v7', with: {'github-token': CODE_TOKEN, script: PLAN_SCRIPT.trim()}}],
    },
  };
  for (const [name, job] of Object.entries(doc.jobs || {})) {
    jobs[name] = {
      needs: 'plan',
      if: "needs.plan.outputs.targets != '[]'",
      ...job,
      strategy: {'fail-fast': false, matrix: {target: '${{ fromJSON(needs.plan.outputs.targets) }}'}},
      steps: [statusStep(name, 'pending'), ...rewriteSteps(job.steps, {ref: '${{ matrix.target.ref }}', file}), statusStep(name, 'result')],
    };
  }
  return {
    name: 'PV-Info checks',
    on: {schedule: [{cron: POLL}], workflow_dispatch: {inputs: {sha: {description: 'Optional PV-Info commit SHA to check now', type: 'string', default: ''}, recheck: {description: 'Check again even if a result was already posted', type: 'boolean', default: false}}}},
    permissions: {contents: 'read'},
    concurrency: {group: 'pv-info-checks', 'cancel-in-progress': false},
    jobs,
  };
}

const PICK_SCRIPT = `
const owner = 'chalamalasetti', repo = 'PV-Info', wanted = '\${{ inputs.ref }}'.trim();
const paths = PATHS;
if (wanted) { core.setOutput('sha', wanted); return; }
const branches = (await github.paginate(github.rest.repos.listBranches, {owner, repo, per_page: 100})).map(b => b.name).filter(n => n === 'main' || n.startsWith('claude/'));
let newest = null;
for (const branch of branches) for (const path of paths) {
  const {data} = await github.rest.repos.listCommits({owner, repo, sha: branch, path, per_page: 1});
  const c = data[0]; if (!c) continue;
  const date = new Date(c.commit.committer.date);
  if (!newest || date > newest.date) newest = {sha: c.sha, date, branch};
}
if (!newest) { core.info('No curation commits found.'); core.setOutput('sha', ''); return; }
let published = new Date(0);
try {
  const r = await fetch('https://api.github.com/repos/\${{ github.repository }}/branches/curated-requirements', {headers: {authorization: 'Bearer \${{ github.token }}'}});
  if (r.ok) published = new Date((await r.json()).commit.commit.committer.date);
} catch (e) { core.warning('Could not read the published branch: ' + e.message); }
core.info(\`Newest curation commit: \${newest.branch} \${newest.sha.slice(0, 7)} at \${newest.date.toISOString()}; last publish \${published.toISOString()}\`);
core.setOutput('sha', newest.date > published ? newest.sha : '');`;

function curatedWorkflow(doc, file) {
  const paths = ['scripts/document-catalog/curation', 'scripts/curation'];
  const [name, job] = Object.entries(doc.jobs)[0];
  return {
    name: doc.name,
    on: {schedule: [{cron: POLL}], workflow_dispatch: {inputs: {ref: {description: 'Optional PV-Info branch or commit to publish now', type: 'string', default: ''}}}},
    permissions: doc.permissions,
    concurrency: doc.concurrency,
    jobs: {
      pick: {
        'runs-on': 'ubuntu-latest',
        outputs: {sha: '${{ steps.pick.outputs.sha }}'},
        steps: [{id: 'pick', name: 'Find the newest curation commit not yet published', uses: 'actions/github-script@v7', with: {'github-token': CODE_TOKEN, script: PICK_SCRIPT.trim().replace('PATHS', JSON.stringify(paths))}}],
      },
      [name]: {needs: 'pick', if: "needs.pick.outputs.sha != ''", ...job, steps: rewriteSteps(job.steps, {ref: '${{ needs.pick.outputs.sha }}', file})},
    },
  };
}

export function buildWorkflow(file, text) {
  if (SKIP.has(file)) return null;
  const doc = parse(text);
  if (!doc || typeof doc !== 'object' || !doc.jobs) return null;
  if (file === 'ci.yml') return ciWorkflow(doc, file);
  if (file === 'curated-requirements.yml') return curatedWorkflow(doc, file);
  const on = keepTriggers(doc.on);
  if (!on) return null;
  const out = {...doc, on};
  out.jobs = Object.fromEntries(Object.entries(doc.jobs).map(([name, job]) => [name, {...job, steps: rewriteSteps(job.steps, {file})}]));
  // Concurrency groups that depended on pull_request no longer need to.
  return out;
}

export function render(file, workflow) {
  return `${MARKER} .github/workflows/${file}.\n# Do not edit here: change the source file in PV-Info; the "Sync jobs from PV-Info" workflow rebuilds this.\n${stringify(workflow, {lineWidth: 0})}`;
}

export function buildAll(src, dest) {
  fs.mkdirSync(dest, {recursive: true});
  const written = new Set();
  for (const file of fs.readdirSync(src).filter(f => /\.ya?ml$/.test(f)).sort()) {
    const workflow = buildWorkflow(file, fs.readFileSync(path.join(src, file), 'utf8'));
    if (!workflow) continue;
    const target = RENAME[file] || file;
    fs.writeFileSync(path.join(dest, target), render(file, workflow));
    written.add(target);
  }
  const removed = [];
  for (const file of fs.readdirSync(dest)) {
    if (written.has(file)) continue;
    const full = path.join(dest, file);
    if (fs.readFileSync(full, 'utf8').startsWith(MARKER)) { fs.rmSync(full); removed.push(file); }
  }
  return {written: [...written], removed};
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [src, dest] = process.argv.slice(2);
  if (!src || !dest) { console.error('usage: build-jobs.mjs <code-repo-workflows-dir> <output-workflows-dir>'); process.exit(2); }
  const {written, removed} = buildAll(src, dest);
  console.log(`Wrote ${written.length} workflows${removed.length ? `, removed ${removed.join(', ')}` : ''}.`);
}
